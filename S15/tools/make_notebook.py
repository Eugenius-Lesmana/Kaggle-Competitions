"""Generate the Kaggle submission notebook from attack.py.

Embeds attack.py as base64 (immune to every quoting/escape failure mode) into
a 2-cell notebook:

  Cell 1: write /kaggle/working/attack.py byte-exact (sha256 round-trip
          verified) + ensure a placeholder submission.csv exists.
  Cell 2: serve JEDAttackInferenceServer ONLY during the hosted rerun
          (KAGGLE_IS_COMPETITION_RERUN set). Ungated serving during an
          interactive "Save & Run All" launches the *local* gateway and tries
          to download ~25 GB of GGUF models — the likely cause of the earlier
          submission failure — so the gate is load-bearing.

Usage:  .venv/bin/python make_notebook.py [attack.py] [submission.ipynb]
"""

from __future__ import annotations

import base64
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent

ATTACK_PATH = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "attack.py"
NOTEBOOK_PATH = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "submission.ipynb"
# Optional third arg: bake ATTACK_MODE into the notebook (the hosted rerun
# never sets it, so a variant notebook MUST pin its MODE explicitly).
BAKED_MODE = sys.argv[3] if len(sys.argv) > 3 else ""

PLACEHOLDER_CSV = "\n".join(
    [
        "Id,Score",
        "gpt_oss_public,0",
        "gpt_oss_private,0",
        "gemma_public,0",
        "gemma_private,0",
        "",
    ]
)


def _cell(source: str) -> dict:
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": source.splitlines(keepends=True),
    }


def main() -> None:
    attack_bytes = ATTACK_PATH.read_bytes()
    attack_b64 = base64.b64encode(attack_bytes).decode("ascii")
    sha = hashlib.sha256(attack_bytes).hexdigest()

    mode_line = (
        f'import os as _os_m\n_os_m.environ["ATTACK_MODE"] = "{BAKED_MODE}"'
        f'  # baked mode: {BAKED_MODE}\n'
        if BAKED_MODE
        else ""
    )
    cell1 = f'''# Cell 1: write attack.py byte-exact + placeholder submission.csv.
# Generated by make_notebook.py from attack.py (sha256 {sha[:16]}…).
{mode_line}import base64
import hashlib
from pathlib import Path

ATTACK_B64 = "{attack_b64}"

data = base64.b64decode(ATTACK_B64)
out = Path("/kaggle/working/attack.py")
out.write_bytes(data)
assert hashlib.sha256(out.read_bytes()).hexdigest() == "{sha}", "attack.py round-trip mismatch"
print("attack.py written:", len(data), "bytes, sha256 ok")

# Placeholder so a scoring-side crash still leaves a parseable CSV.
csv = Path("/kaggle/working/submission.csv")
if not csv.exists():
    csv.write_text({PLACEHOLDER_CSV!r})
print("placeholder submission.csv ensured")
'''

    cell2 = '''# Cell 2: serve the inference server ONLY during the hosted rerun.
# Ungated, this launches the local gateway on interactive runs and tries to
# download ~25 GB of GGUF models — do not remove the gate.
import os

if os.getenv("KAGGLE_IS_COMPETITION_RERUN") is not None:
    import kaggle_evaluation.jed_attack_134815.jed_attack_inference_server as srv

    srv.JEDAttackInferenceServer().run()

print("notebook done; rerun:", bool(os.getenv("KAGGLE_IS_COMPETITION_RERUN")))
'''

    notebook = {
        "cells": [_cell(cell1), _cell(cell2)],
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python", "version": "3.11"},
        },
        "nbformat": 4,
        "nbformat_minor": 4,
    }

    NOTEBOOK_PATH.write_text(json.dumps(notebook, indent=1) + "\n")
    print(f"wrote {NOTEBOOK_PATH} ({NOTEBOOK_PATH.stat().st_size} bytes)")
    print(f"embedded attack.py: {len(attack_bytes)} bytes, sha256 {sha}")

    # Self-check: the notebook we just wrote must decode back to attack.py.
    nb = json.loads(NOTEBOOK_PATH.read_text())
    src = "".join(nb["cells"][0]["source"])
    b64 = src.split('ATTACK_B64 = "', 1)[1].split('"', 1)[0]
    assert hashlib.sha256(base64.b64decode(b64)).hexdigest() == sha, "self-check failed"
    print("self-check ok: notebook decodes back to attack.py")


if __name__ == "__main__":
    main()
